if __name__ == '__main__':
    bad = []
    if len(SHORT) > 30:
        bad.append(f'短标题 {len(SHORT)} 字 > 30')
    for name, t in (('标题', TITLE_MD.split('不写纸质版')[0]), ('描述', DESC_MD)):
        bad += [f'{name}出现禁用词「{w}」' for w in M.BANNED if w in t]
    if bad:
        print('\n'.join(bad))
        sys.exit(1)
    (HERE / '商品标题.md').write_text(TITLE_MD, 'utf-8')
